import { createSupabaseClient } from "./supabase";
import { generateCreativeHypotheses, CreativeRecommendation } from "./creativeBrain";
import { saveCombo, queueComboForDesignPreview } from "./creativeBuilder";
import { getAdSets } from "./metaAds";
import { launchComboToMeta } from "./metaAdsLaunch";
import { reportAutomationStatus } from "./automationStatus";
import { notifySlack } from "./slackNotify";

const CYCLE_DAYS = 7;

// Picks the single most strategically justified recommendation to actually
// build, rather than building every recommendation the Brain returns — the
// Brain itself already said "one strong recommendation beats five mediocre
// ones" in its own prompt, this just enforces that at the autopilot level.
// Must have a voiceover script, since nothing downstream (render queue) can
// proceed without one.
function pickTopRecommendation(recommendations: CreativeRecommendation[]): CreativeRecommendation | null {
  const withScript = recommendations.filter((r) => r.voiceoverScript && r.voiceoverScript.trim());
  if (withScript.length === 0) return null;
  const high = withScript.find((r) => r.priority === "high");
  return high || withScript[0];
}

// Stages 02-05 chained with no human click in between: Brain generates a
// recommendation it already banks to ad_learnings unprompted (Lucky's own
// 2026-09-01 call — that step needs no approval since it takes no real
// external action), this turns the top one straight into a combo with its
// script and design copy already attached, and queues it for render. The
// script is auto-"approved" here in the same spirit — it's just a text
// artifact gating the next internal step, not a real-world action.
//
// The one thing this never does is spend money or go live — see
// autoLaunchReadyCombos below, which only ever creates a PAUSED ad.
export async function runAdsEngineAutopilot(): Promise<{ clientsRun: number; combosCreated: number; errors: string[] }> {
  const sb = createSupabaseClient();
  const errors: string[] = [];
  let combosCreated = 0;

  const cutoff = new Date(Date.now() - CYCLE_DAYS * 24 * 60 * 60 * 1000).toISOString();
  const { data: clients } = await sb
    .from("lq_clients")
    .select("id, name, last_autopilot_cycle_at")
    .eq("status", "active")
    .not("meta_ad_account_id", "is", null);

  const due = (clients || []).filter((c) => !c.last_autopilot_cycle_at || c.last_autopilot_cycle_at < cutoff);

  for (const client of due) {
    try {
      const analysis = await generateCreativeHypotheses(client.id);
      await sb.from("lq_clients").update({ last_autopilot_cycle_at: new Date().toISOString() }).eq("id", client.id);

      const pick = pickTopRecommendation(analysis.recommendations);
      if (!pick) continue;

      const combo = await saveCombo(sb, client.id, {
        offer: pick.offer,
        hypothesis: pick.hypothesis,
        angle: pick.angle,
        hook: pick.hook,
        style: pick.format,
        notes: `Auto-generated by the ads engine autopilot — "${pick.creativeName}". ${pick.whyTesting}`,
      });

      const designBrief = pick.headline && pick.primaryText && pick.cta
        ? { headline: { "1x1": pick.headline, "4x5": pick.headline, "9x16": pick.headline }, primaryText: pick.primaryText, cta: pick.cta }
        : null;

      await sb.from("creative_builder_combos").update({
        script: pick.voiceoverScript,
        script_status: "approved",
        script_drafted_at: new Date().toISOString(),
        design_brief: designBrief,
      }).eq("id", combo.id);

      // Stops here, not at the render queue: Lucky wants to see what an ad
      // will actually look like before it gets built, so this queues the
      // Claude Design preview and waits for his approve/reject in the
      // dashboard — queueComboForRender itself now refuses to run until
      // design_preview_status is "approved" (lib/creativeBuilder.ts).
      await queueComboForDesignPreview(sb, combo.id);
      combosCreated++;
    } catch (e) {
      errors.push(`${client.name}: ${e instanceof Error ? e.message : String(e)}`);
    }
  }

  const summary = `Ran ${due.length} client(s), ${combosCreated} new combo(s) queued for a design preview, ${errors.length} error(s)` + (errors.length ? `: ${errors.join("; ")}` : "");
  await reportAutomationStatus(sb, "ads-engine-autopilot", errors.length ? "error" : "ok", summary);
  if (combosCreated > 0) {
    await notifySlack(`🎬 Ads engine autopilot queued ${combosCreated} new ad concept(s) for a design preview — review in /dashboard/meta-ads once the preview's ready.`);
  }

  return { clientsRun: due.length, combosCreated, errors };
}

// Pure Meta API — no HyperFrames/agent session needed, so this can run on
// every daily-maintenance pass. For every combo with a rendered video
// that hasn't been pushed yet, auto-picks that client's first ACTIVE ad set
// and launches it — always PAUSED (see lib/metaAdsLaunch.ts). This is the
// one place real ad spend could eventually happen, so the PAUSED status is
// the actual safety gate, not a human click on this step.
export async function autoLaunchReadyCombos(): Promise<{ launched: number; errors: string[] }> {
  const sb = createSupabaseClient();
  const errors: string[] = [];
  let launched = 0;

  const { data: combos } = await sb
    .from("creative_builder_combos")
    .select("id, client_id")
    .eq("video_status", "ready")
    .eq("launch_status", "none");

  for (const combo of combos || []) {
    try {
      const { data: client } = await sb.from("lq_clients").select("name, meta_ad_account_id, meta_page_id").eq("id", combo.client_id).maybeSingle();
      if (!client?.meta_ad_account_id || !client?.meta_page_id) continue; // not set up for auto-launch yet, leave for manual push

      const adSets = await getAdSets(client.meta_ad_account_id as string);
      const target = adSets.find((a) => a.status === "ACTIVE") || adSets[0];
      if (!target) {
        errors.push(`${client.name}: no ad sets found to launch into`);
        continue;
      }

      await launchComboToMeta(sb, combo.id, target.id);
      launched++;
    } catch (e) {
      errors.push(`combo ${combo.id}: ${e instanceof Error ? e.message : String(e)}`);
    }
  }

  const summary = `Auto-launched ${launched} ad(s) as PAUSED, ${errors.length} error(s)` + (errors.length ? `: ${errors.join("; ")}` : "");
  await reportAutomationStatus(sb, "ads-engine-auto-launch", errors.length ? "error" : "ok", summary);
  if (launched > 0) {
    await notifySlack(`⏸️ Ads engine auto-launched ${launched} new ad(s) to Meta as PAUSED — review and switch live in Ads Manager when ready.`);
  }

  return { launched, errors };
}
